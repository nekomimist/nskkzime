"""Regenerate the SS3 decoder table from the pinned Unicode mapping file."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/unicode/JIS0212.TXT"
DESTINATION = ROOT / "src/dictionary/jis0212_table.h"
SHA256 = "477820bb3055bbcc90880d788cd95607d221dc94457bae249231adecf13c12e6"


def main():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError("JIS0212.TXT differs from the pinned Unicode table")
    table = [0] * (94 * 94)
    count = 0
    for line in raw.decode("utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        jis, codepoint = (int(field, 16) for field in line.split()[:2])
        row, column = divmod(jis, 256)
        if not (0x21 <= row <= 0x7e and 0x21 <= column <= 0x7e):
            raise ValueError("invalid JIS cell")
        offset = (row - 0x21) * 94 + column - 0x21
        if table[offset] or not (0 < codepoint < 0x10000) or 0xd800 <= codepoint <= 0xdfff:
            raise ValueError("invalid or duplicate Unicode mapping")
        table[offset] = codepoint
        count += 1
    if count != 6067:
        raise ValueError("unexpected mapping count")
    lines = [
        "// Generated by scripts/generate-jis0212.py; do not edit.",
        "// Source: Unicode JIS0212.TXT v2.0 (2015-12-02), 6067 assigned cells.",
        "// Copyright (c) 2015 Unicode, Inc. See third_party/unicode/LICENSE.txt.",
        f"// Source SHA256: {SHA256}",
        "#pragma once",
        "#include <array>",
        "namespace nskkzime::detail {",
        "// Row-major JIS X 0212 grid; zero denotes an unassigned cell.",
        "inline constexpr std::array<char16_t, 94 * 94> jis0212 = {",
    ]
    for offset in range(0, len(table), 16):
        lines.append("    " + ", ".join(f"0x{codepoint:04x}" for codepoint in table[offset:offset + 16]) + ",")
    lines.extend(["};", "}", ""])
    DESTINATION.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Generated {DESTINATION.relative_to(ROOT)}: {count} mappings")


if __name__ == "__main__":
    main()
